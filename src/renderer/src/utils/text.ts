/** 常见文本文件扩展名，用来决定文件列表里要不要显示「编辑」按钮 */
const TEXT_EXTENSIONS = new Set([
  'txt',
  'md',
  'markdown',
  'log',
  'json',
  'jsonc',
  'js',
  'mjs',
  'cjs',
  'jsx',
  'ts',
  'mts',
  'cts',
  'tsx',
  'py',
  'rb',
  'php',
  'go',
  'rs',
  'java',
  'kt',
  'c',
  'h',
  'cpp',
  'hpp',
  'cs',
  'sh',
  'bash',
  'zsh',
  'ksh',
  'fish',
  'ps1',
  'bat',
  'yml',
  'yaml',
  'toml',
  'ini',
  'conf',
  'cfg',
  'env',
  'properties',
  'xml',
  'html',
  'htm',
  'css',
  'scss',
  'less',
  'sql',
  'lua',
  'pl',
  'vue',
  'svelte',
  'dockerfile',
  'makefile',
  'gitignore',
  'editorconfig'
])

export function isTextLike(fileName: string): boolean {
  const dot = fileName.lastIndexOf('.')
  // 没有扩展名（README、Dockerfile）按文本处理
  if (dot <= 0) return true
  return TEXT_EXTENSIONS.has(fileName.slice(dot + 1).toLowerCase())
}
